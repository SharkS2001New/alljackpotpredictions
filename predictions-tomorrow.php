}

// Helper: short label
function getShortPredictionForMarket($type, $prediction) {
    if ($type === '1X2') {
        if (strpos($prediction, 'Home')  !== false) return '1';
        if (strpos($prediction, 'Away')  !== false) return '2';
        if (strpos($prediction, 'Draw')  !== false) return 'X';
    }
    if ($type === 'Over/Under') {
        if (preg_match('/(Over|Under)\s+(\d+\.?\d*)\s+Goals?/i', $prediction, $m)) {
            return $m[1] . ' ' . $m[2];
        }
        if (strpos($prediction, 'Over')  !== false) {
            if (preg_match('/Over\s+(\d+\.?\d*)/i', $prediction, $m)) return 'Over ' . $m[1];
            return 'Over';
        }
        if (strpos($prediction, 'Under') !== false) {
            if (preg_match('/Under\s+(\d+\.?\d*)/i', $prediction, $m)) return 'Under ' . $m[1];
            return 'Under';
        }
    }
    if ($type === 'Double Chance') {
        if ($prediction === 'Home or Away Win') return '12';
        if ($prediction === 'Home Win or Draw') return '1X';
        if ($prediction === 'Draw or Away Win') return 'X2';
    }
    if ($type === 'BTTS') {
        if (strpos($prediction, 'Both')    !== false) return 'GG';
        if (strpos($prediction, 'No Goal') !== false) return 'NG';
    }
    return substr($prediction, 0, 8);
}

