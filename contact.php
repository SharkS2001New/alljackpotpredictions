(function () {
  var form    = document.getElementById('contactForm');
  var success = document.getElementById('conFormSuccess');
  var btnText = document.getElementById('con-btn-text');
  var btnArr  = document.getElementById('con-btn-arrow');

  if (!form) return;

  form.addEventListener('submit', function (e) {
    e.preventDefault();

    /* Basic validation */
    var name     = document.getElementById('con-name').value.trim();
    var email    = document.getElementById('con-email').value.trim();
    var subject  = document.getElementById('con-subject').value;
    var message  = document.getElementById('con-message').value.trim();
    var consent  = document.getElementById('con-consent').checked;

    if (!name || !email || !subject || !message || !consent) {
      /* Highlight empty required fields */
      ['con-name','con-email','con-subject','con-message'].forEach(function (id) {
        var el = document.getElementById(id);
        if (!el.value.trim()) {
          el.style.borderColor = 'var(--pink)';
          el.addEventListener('input', function () {
            el.style.borderColor = '';
          }, { once: true });
        }
      });
      if (!consent) {
        document.getElementById('con-consent').style.outline = '2px solid var(--pink)';
        document.getElementById('con-consent').addEventListener('change', function () {
          this.style.outline = '';
        }, { once: true });
      }
      return;
    }

    /* Loading state */
    btnText.textContent = 'Sending…';
    btnArr.textContent  = '⏳';

    /*
     * ── Server-side integration ──────────────────────────────────────────
     * Replace the setTimeout below with a real fetch() to your PHP endpoint.
     * Example:
     *
     * fetch('/contact-handler.php', {
     *   method: 'POST',
     *   headers: { 'Content-Type': 'application/json' },
     *   body: JSON.stringify({ name, email, subject, message })
     * })
     * .then(r => r.json())
     * .then(data => {
     *   if (data.success) showSuccess();
     *   else showError();
     * })
     * .catch(showError);
     * ─────────────────────────────────────────────────────────────────────
     */
    setTimeout(function () {
      form.style.display   = 'none';
      success.classList.add('visible');
    }, 900);
  });
}());
