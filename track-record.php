// Pagination and filtering for results table
const rows = document.querySelectorAll('#tr-results-body tr');
const prevBtn = document.getElementById('tr-prev');
const nextBtn = document.getElementById('tr-next');
const pageButtons = document.querySelectorAll('#tr-pg-controls .pg-num');
let currentPage = 1;
const rowsPerPage = 10;

function filterAndPaginate() {
  const resultFilter = document.getElementById('tr-fsel-result').value;
  const leagueFilter = document.getElementById('tr-fsel-league').value;
  
  let visibleRows = [];
  rows.forEach(row => {
    const result = row.getAttribute('data-result');
    const league = row.getAttribute('data-league');
    let show = true;
    if (resultFilter && result !== resultFilter) show = false;
    if (leagueFilter && league !== leagueFilter) show = false;
    if (show) visibleRows.push(row);
    row.style.display = 'none';
  });
  
  const totalVisible = visibleRows.length;
  const totalPages = Math.ceil(totalVisible / rowsPerPage);
  currentPage = Math.min(currentPage, totalPages);
  if (currentPage < 1) currentPage = 1;
  
  const start = (currentPage - 1) * rowsPerPage;
  const end = start + rowsPerPage;
  visibleRows.slice(start, end).forEach(row => row.style.display = '');
  
  const startNum = start + 1;
  const endNum = Math.min(end, totalVisible);
  document.getElementById('tr-pg-info').innerText = `Showing ${startNum}–${endNum} of ${totalVisible} results`;
  document.getElementById('tr-count').innerText = totalVisible + ' results';
  
  prevBtn.disabled = currentPage === 1;
  nextBtn.disabled = currentPage === totalPages || totalPages === 0;
  
  pageButtons.forEach(btn => {
    const page = parseInt(btn.getAttribute('data-page'));
    if (page === currentPage) {
      btn.classList.add('pg-active');
    } else {
      btn.classList.remove('pg-active');
    }
    btn.style.display = page <= totalPages ? 'inline-block' : 'none';
  });
}

const resultFilter = document.getElementById('tr-fsel-result');
const leagueFilter = document.getElementById('tr-fsel-league');
if (resultFilter) resultFilter.addEventListener('change', () => { currentPage = 1; filterAndPaginate(); });
if (leagueFilter) leagueFilter.addEventListener('change', () => { currentPage = 1; filterAndPaginate(); });

if (prevBtn) prevBtn.addEventListener('click', () => {
  if (currentPage > 1) { currentPage--; filterAndPaginate(); }
});
if (nextBtn) nextBtn.addEventListener('click', () => {
  const visibleCount = Array.from(rows).filter(row => {
    const result = row.getAttribute('data-result');
    const league = row.getAttribute('data-league');
    let show = true;
    if (resultFilter?.value && result !== resultFilter.value) show = false;
    if (leagueFilter?.value && league !== leagueFilter.value) show = false;
    return show;
  }).length;
  const totalPages = Math.ceil(visibleCount / rowsPerPage);
  if (currentPage < totalPages) { currentPage++; filterAndPaginate(); }
});

pageButtons.forEach(btn => {
  btn.addEventListener('click', () => {
    currentPage = parseInt(btn.getAttribute('data-page'));
    filterAndPaginate();
  });
});

filterAndPaginate();
