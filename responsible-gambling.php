      <div class="rgp-sign-icon">💸</div>
      <div class="rgp-sign-title">Chasing losses</div>
      <p class="rgp-sign-body">Placing bets specifically to win back money you've already lost — often with bigger stakes than usual. This is one of the most common and most damaging patterns in problem gambling.</p>
    </div>
    <div class="rgp-sign-card">
      <div class="rgp-sign-icon">🔁</div>
      <div class="rgp-sign-title">Unable to stop or take a break</div>
      <p class="rgp-sign-body">Feeling an urge to bet even when you intended to stop, or finding it difficult to go a day or week without gambling without feeling anxious or restless.</p>
    </div>
    <div class="rgp-sign-card">
      <div class="rgp-sign-icon">🤫</div>
      <div class="rgp-sign-title">Hiding your gambling</div>
      <p class="rgp-sign-body">Feeling the need to hide bets, winnings or losses from family or friends — or lying about the amount of time or money you spend on gambling.</p>
    </div>
    <div class="rgp-sign-card">
      <div class="rgp-sign-icon">📉</div>
      <div class="rgp-sign-title">Betting money you can't afford to lose</div>
      <p class="rgp-sign-body">Using money set aside for bills, food, rent or other essential expenses to fund gambling. Borrowing money specifically to place bets.</p>
    </div>
    <div class="rgp-sign-card">
      <div class="rgp-sign-icon">🧠</div>
      <div class="rgp-sign-title">Gambling dominates your thoughts</div>
      <p class="rgp-sign-body">Spending significant parts of your day thinking about past bets, planning future ones or calculating winnings — even when you're at work, with family or trying to sleep.</p>
    </div>
    <div class="rgp-sign-card">
      <div class="rgp-sign-icon">⬆️</div>
      <div class="rgp-sign-title">Needing bigger bets for the same thrill</div>
      <p class="rgp-sign-body">Finding that you need to place larger or riskier bets to feel the same excitement — a pattern similar to tolerance in substance use disorders.</p>
    </div>
  </div>

  <p style="font-family:var(--fsans);font-size:.8rem;line-height:1.8;color:var(--body);margin-top:16px;">
    If you recognise any of these signs in yourself or someone close to you, the organisations in the
    <a href="#support" style="color:var(--pink);font-weight:700">Support section below</a> offer free, confidential help.
    You don't need to have hit rock bottom to reach out — the earlier, the easier.
